"""Alembic migration behavior and the PostgreSQL objects autogenerate cannot compare."""

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import CheckConstraint, Connection, Engine, inspect, text

from kavach.db.models import Base

from .conftest import alembic_config

pytestmark = pytest.mark.integration

DOCUMENTED_TABLES = {
    "users",
    "sessions",
    "ingest_keys",
    "events",
    "incidents",
    "incident_events",
    "assessments",
    "reviews",
    "audit_records",
}
DEFERRED_TRIGGERS = {
    ("incident_events", "incident_events_integrity"),
    ("incidents", "incidents_integrity"),
    ("assessments", "assessments_integrity"),
    ("events", "events_integrity"),
}


def current_revision(connection: Connection) -> str:
    return connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one()


def test_single_initial_revision() -> None:
    script = ScriptDirectory.from_config(alembic_config())
    assert [revision.revision for revision in script.walk_revisions()] == ["0001_initial_schema"]


def test_upgrade_from_empty_creates_exactly_the_documented_tables(
    migrated_schema: None, migration_engine: Engine
) -> None:
    tables = set(inspect(migration_engine).get_table_names())
    assert tables - {"alembic_version"} == DOCUMENTED_TABLES
    assert set(Base.metadata.tables) == DOCUMENTED_TABLES
    with migration_engine.connect() as connection:
        assert current_revision(connection) == "0001_initial_schema"


def test_repeated_upgrade_is_a_no_op_and_metadata_matches(
    migrated_schema: None, migration_engine: Engine
) -> None:
    command.upgrade(alembic_config(), "head")
    command.upgrade(alembic_config(), "head")
    # Raises AutogenerateDiffsDetected if the models and the migrated database disagree.
    command.check(alembic_config())
    with migration_engine.connect() as connection:
        assert current_revision(connection) == "0001_initial_schema"


def test_downgrade_is_refused_without_naming_the_disposable_database(
    migrated_schema: None, migration_engine: Engine
) -> None:
    with pytest.raises(RuntimeError, match="Refusing to drop the KAVACH schema"):
        command.downgrade(alembic_config(), "base")
    assert DOCUMENTED_TABLES <= set(inspect(migration_engine).get_table_names())


def test_downgrade_and_upgrade_round_trip_on_the_disposable_database(
    migrated_schema: None, migration_engine: Engine
) -> None:
    try:
        command.downgrade(alembic_config(allow_downgrade=True), "base")
        remaining = set(inspect(migration_engine).get_table_names())
        assert remaining & DOCUMENTED_TABLES == set()
        with migration_engine.connect() as connection:
            functions = connection.execute(
                text("SELECT count(*) FROM pg_proc WHERE proname LIKE 'kavach\\_%'")
            ).scalar_one()
        assert functions == 0
    finally:
        command.upgrade(alembic_config(), "head")
    assert DOCUMENTED_TABLES <= set(inspect(migration_engine).get_table_names())


def test_check_constraints_match_the_models(owner_tx: Connection) -> None:
    # `alembic check` does not compare CHECK constraints, so compare their names explicitly.
    database = set(
        owner_tx.execute(
            text(
                "SELECT conname FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace"
                " WHERE n.nspname = 'public' AND c.contype = 'c'"
            )
        ).scalars()
    )
    models = {
        constraint.name
        for table in Base.metadata.tables.values()
        for constraint in table.constraints
        if isinstance(constraint, CheckConstraint)
    }
    assert database == models
    assert len(models) == 35


def test_circular_foreign_keys_are_deferred(owner_tx: Connection) -> None:
    rows = owner_tx.execute(
        text(
            "SELECT conname, condeferrable, condeferred FROM pg_constraint"
            " WHERE conrelid = 'incidents'::regclass AND contype = 'f' ORDER BY conname"
        )
    ).all()
    assert [tuple(row) for row in rows] == [
        ("fk_incidents_id_current_revision_assessments", True, True),
        ("fk_incidents_id_latest_review_id_reviews", True, True),
    ]


def test_integrity_triggers_are_deferred_constraint_triggers(owner_tx: Connection) -> None:
    rows = owner_tx.execute(
        text(
            "SELECT c.relname, t.tgname, t.tgdeferrable, t.tginitdeferred FROM pg_trigger t"
            " JOIN pg_class c ON c.oid = t.tgrelid"
            " WHERE NOT t.tgisinternal AND t.tgconstraint <> 0"
        )
    ).all()
    assert {(row[0], row[1]) for row in rows} == DEFERRED_TRIGGERS
    assert all(row[2] and row[3] for row in rows)
    updated_at = owner_tx.execute(
        text("SELECT count(*) FROM pg_trigger WHERE tgname = 'users_set_updated_at'")
    ).scalar_one()
    assert updated_at == 1


@pytest.mark.parametrize(
    "signature",
    [
        "kavach_check_incident_integrity(uuid)",
        "kavach_incident_integrity_trigger()",
        "kavach_set_updated_at()",
    ],
)
def test_trigger_functions_are_not_callable_by_application_roles(
    owner_tx: Connection, signature: str
) -> None:
    for role in ("kavach_app", "kavach_retention"):
        allowed = owner_tx.execute(
            text("SELECT has_function_privilege(:role, :signature, 'EXECUTE')"),
            {"role": role, "signature": signature},
        ).scalar_one()
        assert allowed is False


def test_security_definer_functions_pin_their_search_path(owner_tx: Connection) -> None:
    rows = owner_tx.execute(
        text("SELECT proname, proconfig FROM pg_proc WHERE prosecdef AND proname LIKE 'kavach\\_%'")
    ).all()
    assert {row[0] for row in rows} == {
        "kavach_check_incident_integrity",
        "kavach_incident_integrity_trigger",
    }
    assert all(row[1] == ["search_path=pg_catalog, pg_temp"] for row in rows)
